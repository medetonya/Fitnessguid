const transliterateLatin = (value: string) => {
  return value.replace(/[A-Za-z]+/g, (token) => {
    const lower = token.toLowerCase()
    let out = ''
    for (const ch of lower) {
      out += translitMap[ch] ?? ch
    }
    return out
  })
}

const applyPhraseMap = (value: string, phraseMap: Array<[string, string]>) => {
  let out = value
  for (const [from, to] of phraseMap) {
    out = out.replaceAll(from, to)
  }
  return out
}


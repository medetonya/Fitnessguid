const autoTranslateTechniqueToRu = (technique: string): string | null => {
  if (!technique.trim()) {
    return null
  }

  let out = technique

  for (const [pattern, replacement] of techniqueHeadingMap) {
    out = out.replace(pattern, replacement)
  }

  for (const [from, to] of techniquePhraseMap) {
    out = out.replaceAll(from, to)
  }

  out = out
    .replace(/\bStand\b/g, 'Встаньте')
    .replace(/\bSit\b/g, 'Сядьте')
    .replace(/\bLie\b/g, 'Лягте')
    .replace(/\bHold\b/g, 'Удерживайте')
    .replace(/\bKeep\b/g, 'Сохраняйте')
    .replace(/\bSqueeze\b/g, 'Сожмите')
    .replace(/\bLower\b/g, 'Опускайте')
    .replace(/\bLift\b/g, 'Поднимайте')
    .replace(/\bRaise\b/g, 'Поднимайте')
    .replace(/\bPull\b/g, 'Тяните')
    .replace(/\bPush\b/g, 'Жмите')
    .replace(/\bSlowly\b/g, 'Медленно')
    .replace(/\bPause\b/g, 'Пауза')
    .replace(/\bReturn\b/g, 'Вернитесь')

  return enforceMidBackRu(out)
}

const exerciseNameRuMap = new Map<string, string>(
  exercisePhraseMap.map(([from, to]) => [normalizeExerciseName(from), to])
)

const normalizeLocalizedName = (name: string) => name.toLowerCase().replace(/[^a-zа-яё0-9]+/gi, ' ').trim()

const exerciseNameEnMap = new Map<string, string>()
for (const [enName, ruName] of exercisePhraseMap) {
  const key = normalizeLocalizedName(ruName)
  if (!exerciseNameEnMap.has(key)) {
    exerciseNameEnMap.set(key, enName)
  }
}

export function localizeExerciseName(name: string, language: string): string {
  if (language === 'en') {
    const backToEnglish = exerciseNameEnMap.get(normalizeLocalizedName(name))
    return backToEnglish ?? name
  }

  if (language !== 'ru') {
    return name
  }

  const direct = exerciseNameRuMap.get(normalizeExerciseName(name))
  if (direct) {
    return direct
  }

  const resolved = exerciseNameRuMap.get(resolveExerciseContentKey(name))
  if (resolved) {
    return resolved
  }

  return name
}

export function localizeExerciseZone(zone: string | undefined, language: string): string {
  if (!zone) {
    return ''
  }
  if (language !== 'ru') {
    return zone
  }

  let localized = applyPhraseMap(zone, zonePhraseMap)
  if (!containsCyrillic(localized) || /[A-Za-z]/.test(localized)) {
    localized = transliterateLatin(localized)
  }

  localized = enforceMidBackRu(localized)

  return localized
}

export function localizeMusclesText(muscles: string | undefined, language: string): string {
  if (!muscles) {
    return ''
  }
  if (language !== 'ru') {
    return muscles
  }

  let localized = applyPhraseMap(muscles, musclesPhraseMap)
  localized = enforceMidBackRu(localized)
  localized = localized.replace(/\s+,/g, ',').replace(/,,+/g, ',').trim()

  return localized
}

export function localizeRepsText(reps: string, language: string): string {
  if (language === 'ru') {
    return reps
      .replace(/(\d+)\s*each\s*leg/gi, '$1 на каждую ногу')
      .replace(/(\d+)\s*each\s*side/gi, '$1 на каждую сторону')
      .replace(/\beach\s*leg\b/gi, 'на каждую ногу')
      .replace(/\beach\s*side\b/gi, 'на каждую сторону')
      .replace(/\bsec\b/gi, 'сек')
      .replace(/\bseconds?\b/gi, 'сек')
      .replace(/\bkg\b/gi, 'кг')
  }

  return reps
    .replace(/(\d+)\s*на\s*каждую\s*ногу/gi, '$1 each leg')
    .replace(/(\d+)\s*на\s*каждую\s*сторону/gi, '$1 each side')
    .replace(/на\s*каждую\s*ногу/gi, 'each leg')
    .replace(/на\s*каждую\s*сторону/gi, 'each side')
    .replace(/\bсек\.?\b/gi, 'sec')
    .replace(/\bкг\b/gi, 'kg')
}

export function localizeTechniqueText(
  technique: string | undefined,
  _tag: BuilderExerciseTag | undefined,
  exerciseName: string | undefined,
  language: string
): string | undefined {
  if (!technique) {
    return technique
  }
  if (language !== 'ru') {
    return technique
  }
  // Keep already fully Russian text untouched.
  if (containsCyrillic(technique) && !/[A-Za-z]/.test(technique)) {
    return technique
  }

  if (exerciseName) {
    const byDirectName = exerciseTechniqueRuByName[normalizeExerciseName(exerciseName)]
    if (byDirectName) {
      return byDirectName
    }

    const byResolvedName = exerciseTechniqueRuByName[resolveExerciseContentKey(exerciseName)]
    if (byResolvedName) {
      return byResolvedName
    }
  }

  const autoTranslated = autoTranslateTechniqueToRu(technique)
  if (autoTranslated && containsCyrillic(autoTranslated) && !/[A-Za-z]/.test(autoTranslated)) {
    return autoTranslated
  }

  // Do not replace exercise-specific technique with generic templates.
  // If full RU conversion is not possible, return the original exercise text.
  return technique
}

const resolveRuTechnique = (technique: string): string | null => {
  for (const [signature, ruText] of techniqueRuBySignature) {
    if (technique.includes(signature)) {
      return ruText
    }
  }
  return null
}

const getRuTemplateBySignature = (signature: string): string | null => {
  for (const [sig, ruText] of techniqueRuBySignature) {
    if (sig === signature) {
      return ruText
    }
  }
  return null
}

const resolveRuTechniqueByExerciseName = (
  exerciseName: string,
  tag: BuilderExerciseTag | undefined
): string | null => {
  const normalized = normalizeExerciseName(exerciseName)

  if (normalized.includes('hip thrust') || normalized.includes('glute bridge')) {
    return getRuTemplateBySignature('Set your upper back against a bench or pad')
  }

  if (
    normalized.includes('kickback') ||
    normalized.includes('abduction') ||
    normalized.includes('adduction') ||
    normalized.includes('clamshell')
  ) {
    return getRuTemplateBySignature('Stabilize your pelvis and core before moving')
  }

  if (
    normalized.includes('squat') ||
    normalized.includes('lunge') ||
    normalized.includes('leg press') ||
    normalized.includes('step up')
  ) {
    return getRuTemplateBySignature('Place feet about shoulder-width apart with whole foot grounded')
  }

  if (normalized.includes('leg extension')) {
    return getRuTemplateBySignature('Adjust the machine so your knees align with the rotation axis')
  }

  if (normalized.includes('leg curl')) {
    return getRuTemplateBySignature('Adjust the pad so it rests comfortably just above your ankles')
  }

  if (normalized.includes('deadlift') || normalized.includes('romanian') || normalized.includes('good morning')) {
    return getRuTemplateBySignature('Stand with neutral spine, soft knees, and shoulders packed')
  }

  if (normalized.includes('row') || normalized.includes('pulldown') || normalized.includes('pull up')) {
    return getRuTemplateBySignature('Set your torso stable and keep your chest open')
  }

  if (normalized.includes('fly') || normalized.includes('pec deck')) {
    return getRuTemplateBySignature('Set your shoulders down and back. Maintain a slight bend in your elbows')
  }

  if (normalized.includes('press') || normalized.includes('push up') || normalized.includes('dip')) {
    return getRuTemplateBySignature('Set shoulders down and back with stable core tension')
  }

  if (normalized.includes('curl') || normalized.includes('triceps') || normalized.includes('pushdown') || normalized.includes('skull')) {
    return getRuTemplateBySignature('Position yourself with elbows fixed and upper arm stable')
  }

  if (normalized.includes('raise') || normalized.includes('face pull')) {
    return getRuTemplateBySignature('Use a light to moderate load. Set a stable shoulder')
  }

  if (normalized.includes('plank') || normalized.includes('crunch') || normalized.includes('twist') || normalized.includes('woodchopper')) {
    return getRuTemplateBySignature('Brace your abs and set your lower back in a neutral position')
  }

  if (normalized.includes('calf')) {
    return getRuTemplateBySignature('Position your forefoot on the edge of a platform')
  }

  if (
    normalized.includes('burpee') ||
    normalized.includes('mountain climber') ||
    normalized.includes('jumping jack') ||
    normalized.includes('high knees')
  ) {
    return getRuTemplateBySignature('Begin with an active core and neutral posture')
  }

  if (tag && defaultRuTechniqueByTag[tag]) {
    return defaultRuTechniqueByTag[tag]
  }

  return null
}


const getValueByPath = (tree: TranslationTree, key: string): string | undefined => {
  const value = key.split('.').reduce<string | TranslationTree | undefined>((acc, part) => {
    if (!acc || typeof acc === 'string') {
      return undefined
    }

    return acc[part]
  }, tree)

  return typeof value === 'string' ? value : undefined
}

export const tForLanguage = (language: Language, key: string): string => {
  const current = getValueByPath(translations[language], key)
  if (current) {
    return current
  }

  const fallback = getValueByPath(translations.en, key)
  return fallback ?? key
}

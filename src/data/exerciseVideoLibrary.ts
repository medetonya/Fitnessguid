export function getExerciseVideoUrl(exerciseName: string, context?: ExerciseVideoContext): string | undefined {
  const normalized = normalizeExerciseName(exerciseName)
  const canonicalKey = exerciseVideoAliases[normalized] ?? normalized

  if (context) {
    return exerciseVideoMap[context][canonicalKey] ?? exerciseVideoMap.shared[canonicalKey]
  }

  return exerciseVideoMap.shared[canonicalKey]
}

export function setExerciseVideoUrl(
  exerciseName: string,
  videoUrl: string,
  context: ExerciseVideoContext | 'shared' = 'shared',
  map: ExerciseVideoLibrary = exerciseVideoMap
) {
  map[context][normalizeExerciseName(exerciseName)] = videoUrl
}

